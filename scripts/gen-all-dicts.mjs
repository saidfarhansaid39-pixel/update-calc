// Get remaining titles for each locale
function getRemaining(locale) {
  const d = JSON.parse(readFileSync(join(BASE, locale + '.json'), 'utf-8'));
  const rem = [];
  for (const k of Object.keys(en)) {
    if (d[k] && d[k].title === en[k].title) rem.push(en[k].title);
  }
  return rem;
}

// Build word dictionary for a locale
function buildDict(locale, translator) {
  const remaining = getRemaining(locale);
  const words = new Set();
  for (const title of remaining) {
    const parts = title.split(/[\s\/\-\(\)]+/);
    for (const w of parts) {
      if (/^[A-Z]/.test(w) && w.length > 1 && !/^[A-Z0-9]{2,5}$/.test(w)) {
        words.add(w);
      }
    }
  }
  const dict = {};
  for (const w of words) {
    dict[w] = translator(w);
  }
  return dict;
}

