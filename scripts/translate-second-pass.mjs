// Also add systematic patterns
const SYSTEMATIC = {
  es: { calculator: 'Calculadora', converter: 'Convertidor', counter: 'Contador' },
  fr: { calculator: 'Calculatrice', converter: 'Convertisseur', counter: 'Compteur' },
  de: { calculator: 'Rechner', converter: 'Konverter', counter: 'Zähler' },
  pt: { calculator: 'Calculadora', converter: 'Conversor', counter: 'Contador' },
  ar: { calculator: 'آلة حاسبة', converter: 'محول', counter: 'عداد' },
}

function translateWordByWord(title, locale) {
  const dict = DICT[locale]
  const sys = SYSTEMATIC[locale]
  if (!dict) return null

  const words = title.split(/(\s+)/)
  let changed = false
  const result = words.map(w => {
    const t = w.trim()
    if (t.length === 0) return w
    // direct match
    if (dict[t]) { changed = true; return w.replace(t, dict[t]) }
    // number-suffix match: "Premium Credit 3"
    const numMatch = t.match(/^(\D+?)\s*(\d+)$/)
    if (numMatch && dict[numMatch[1]]) { changed = true; return w.replace(t, dict[numMatch[1]] + ' ' + numMatch[2]) }
    // hyphenated match: "Body-fat"
    const hyphenMatch = t.match(/^(.+)-(.+)$/)
    if (hyphenMatch) {
      const t1 = dict[hyphenMatch[1]] || hyphenMatch[1]
      const t2 = dict[hyphenMatch[2]] || hyphenMatch[2]
      if (dict[hyphenMatch[1]] || dict[hyphenMatch[2]]) { changed = true; return w.replace(t, t1 + '-' + t2) }
    }
    // systematic patterns: "X Calculator" -> "X Calculadora"
    for (const [en, loc] of Object.entries(sys)) {
      if (t.toLowerCase() === en.toLowerCase()) { changed = true; return w.replace(new RegExp(t, 'i'), loc) }
    }
    return w
  }).join('')
  return changed ? result : null
}

async function main() {
  const { calculatorRegistry } = await import('@calcuniverse/calculator-registry')
  const regSlugs = new Set(calculatorRegistry.map(e => e.slug))

  for (const locale of LOCALES) {
    const path = join(OVERRIDES_DIR, locale + '.json')
    const existing = JSON.parse(readFileSync(path, 'utf-8'))
    let translated = 0

    for (const [slug, ov] of Object.entries(existing)) {
      if (!regSlugs.has(slug)) continue
      // only process titles that are still fully Latin-ASCII (i.e., potentially English)
      if (!/^[A-Za-z0-9\s\-'(),.:!?/]+$/.test(ov.title)) continue
      const newTitle = translateWordByWord(ov.title, locale)
      if (newTitle && newTitle !== ov.title) {
        existing[slug] = { title: newTitle, description: ov.description }
        translated++
      }
    }

    writeFileSync(path, JSON.stringify(existing, null, 2) + '\n', 'utf-8')

    const remaining = Object.entries(existing)
      .filter(([k, v]) => regSlugs.has(k) && /^[A-Za-z0-9\s\-'(),.:!?/]+$/.test(v.title)).length
    console.log(`${locale}: ${translated} translated, ${remaining} still Latin-only`)
  }
}

main().catch(err => { console.error(err); process.exit(1) })
