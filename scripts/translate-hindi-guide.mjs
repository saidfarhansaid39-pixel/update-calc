// Build sorted word list (longest first)
const WORD_ENTRIES = Object.entries(WORDS).sort((a, b) => b[0].length - a[0].length)

function translateLongTail(text) {
  if (!text || typeof text !== 'string') return text
  // Preserve template variables
  const vars = []
  let processed = text.replace(/\{(\w+)\}/g, (m) => {
    vars.push(m)
    return `\x00${vars.length - 1}\x00`
  })

  // Word-level replacement
  for (const [en, hi] of WORD_ENTRIES) {
    const idx = processed.toLowerCase().indexOf(en.toLowerCase())
    if (idx >= 0) {
      const before = idx > 0 ? processed[idx - 1] : ' '
      const afterPos = idx + en.length
      const after = afterPos < processed.length ? processed[afterPos] : ' '
      if (!/[a-zA-Z]/.test(before) && !/[a-zA-Z]/.test(after)) {
        processed = processed.slice(0, idx) + hi + processed.slice(afterPos)
      }
    }
  }

  // Restore variables
  vars.forEach((v, i) => { processed = processed.replace(`\x00${i}\x00`, v) })
  return processed
}

// ─────────────────────────────────────────
// 3. Apply translations
// ─────────────────────────────────────────

let exactDone = 0, longTailDone = 0, unchanged = 0

function applyTranslation(obj, path) {
  if (!obj || typeof obj !== 'object') return
  for (const key of Object.keys(obj)) {
    const fullPath = path ? `${path}.${key}` : key
    const value = obj[key]
    if (typeof value === 'string') {
      // Try exact match first
      if (EXACT[fullPath] !== undefined) {
        if (obj[key] !== EXACT[fullPath]) {
          obj[key] = EXACT[fullPath]
          exactDone++
        }
      } else {
        // Long tail - only if still English
        const translated = translateLongTail(value)
        if (translated !== value) {
          obj[key] = translated
          longTailDone++
        } else {
          unchanged++
        }
      }
    } else if (typeof value === 'object') {
      applyTranslation(value, fullPath)
    }
  }
}

